#!/usr/bin/env python3
"""Generate the sample classes used by the bonus component-scanning experiment."""

from pathlib import Path


CLASS_COUNT = 1000
ANNOTATION_INTERVAL = 10
PACKAGE = "com.example.bonus.samples"
PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = PROJECT_ROOT / "src" / "main" / "java" / Path(*PACKAGE.split("."))


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    for number in range(1, CLASS_COUNT + 1):
        class_name = f"Sample{number:04d}"
        source = f"// Generated by scripts/generate_bonus_classes.py.\npackage {PACKAGE};\n\n"

        if number % ANNOTATION_INTERVAL == 0:
            source += "import com.example.bonus.MyComponent;\n\n@MyComponent\n"

        source += f"public class {class_name} {{\n}}\n"
        (OUTPUT_DIR / f"{class_name}.java").write_text(source, encoding="utf-8")

    print(
        f"Generated {CLASS_COUNT} classes in {OUTPUT_DIR}\n"
        f"Annotated {CLASS_COUNT // ANNOTATION_INTERVAL} classes with @MyComponent."
    )


if __name__ == "__main__":
    main()
